import assert from "node:assert/strict";
import {fromGeojsonVt} from "@maplibre/vt-pbf";
import {normalizeActiveFault, buildActiveFaultPreset, isInterplateSimulation} from "../src/simulation/activeFault.js";
import {loadActiveFaultCatalog, readActiveFaultTile} from "../src/simulation/activeFaultCatalog.js";
import {normalizeSimulationOptions, buildSimulationSources, prepareEarthquakeSimulation} from "../src/simulation/earthquakeSimulation.js";
import {estimateReferenceIntensity} from "../src/simulation/intensityModel.js";
import {getDistanceKm} from "../src/location/distance.js";

// Synthetic records, not a reproduction of the provider's catalogue.
const fault = {FLT_ID:"F01220C_00002",LTENAME:"試験断層",LON:"135.5",LAT:"34.5",DEP:"2",LEN:"40",WID:"18",STR:"20",DIP:"60",MAG:"-7"};
const preset=buildActiveFaultPreset(fault);
assert.equal(preset.magnitudeValue,7);
assert.equal(preset.depthKm,10);
assert.ok(Math.abs(preset.lengthKm-40)<.01);
assert.ok(getDistanceKm(preset.areaSides.left[0],preset.areaSides.right[0])>8.9);
const reverse=buildActiveFaultPreset({...fault,DIP:150});
assert.equal(reverse.depthKm,7);
assert.ok(reverse.path[0][0]<Number(fault.LON),"obtuse dip keeps the original opposite dipping direction");
assert.equal(buildActiveFaultPreset({...fault,MAG:7}).magnitudeValue,null,"Mj is never silently treated as Mw");
assert.equal(buildActiveFaultPreset({...fault,MAG:""}).magnitudeValue,null);
for(const change of [{FLT_ID:"<script>"},{DEP:""},{DEP:-999},{LEN:0},{DIP:181},{LAT:null}])assert.throws(()=>normalizeActiveFault({...fault,...change}),RangeError);
assert.throws(()=>normalizeSimulationOptions({model:"active-fault"}),RangeError);
const options={model:"active-fault",activeFault:fault,longitude:preset.longitude,latitude:preset.latitude,magnitude:7,depthKm:preset.depthKm};
assert.equal(isInterplateSimulation(options),false);assert.equal(isInterplateSimulation({model:"nankai-trough"}),true);
const sources=buildSimulationSources(options);
assert.ok(sources.length>2);
assert.equal(sources.find(source=>source.ruptureDelaySec===0).coordinates.length,2);
assert.equal(buildSimulationSources({...options,ruptureOrigin:"start"})[0].ruptureDelaySec,0);
assert.equal(buildSimulationSources({...options,ruptureOrigin:"end"}).at(-1).ruptureDelaySec,0);
const stations={a:{code:"001",name:"試験観測点",longitude:135.6,latitude:34.6},b:{code:"002",name:"遠方",longitude:139,latitude:36}};
const simulation=await prepareEarthquakeSimulation(options,stations);
assert.equal(simulation.name,fault.LTENAME);
for(const station of simulation.stations) assert.equal(station.predictedIntensityValue,estimateReferenceIntensity({magnitude:7,depthKm:preset.depthKm,ruptureDistanceKm:Math.hypot(station.epicentralDistanceKm,preset.depthKm),interplate:false}));
assert.equal(simulation.frame(0).event.magnitude,null);
const last=simulation.frame(simulation.duration);
assert.equal(last.event.magnitude,7);assert.equal(last.event.depth,preset.depthKm);assert.equal(last.event.isFinal,true);
assert.equal(last.fault.features[0].geometry.type,"Polygon");
const vertical=await prepareEarthquakeSimulation({...options,activeFault:{...fault,DIP:90}},stations);
assert.equal(vertical.frame(0).fault.features[0].geometry.type,"LineString","vertical planes do not become invalid zero-area polygons");

const tile=(properties)=>fromGeojsonVt({major_fault:{features:properties.map(tags=>({type:3,geometry:[[[0,0],[10,0],[10,10],[0,0]]],tags}))}});
const bytes=tile([fault,fault,{...fault,FLT_ID:"F000001_00001",LTENAME:"北の試験断層",LAT:43},{...fault,DEP:""}]);
assert.equal(readActiveFaultTile(bytes).length,3);
let requests=0;
const fetcher=async url=>{requests++;assert.match(url,/^https:\/\/www\.j-shis\.bosai\.go\.jp\/map\/xyz\/major_fault\/Y2022\/MAX\/4\/1[34]\/[56]\.mvt\?lang=ja$/);return new Response(bytes);};
const catalog=await loadActiveFaultCatalog({fetcher});
assert.equal(requests,4);assert.equal(catalog.length,2,"one tile feature per FLT_ID, regardless of tile clipping or duplicates");
assert.equal(catalog[0].LTENAME,"北の試験断層");
await assert.rejects(loadActiveFaultCatalog({fetcher:async()=>new Response("unavailable",{status:503})}),/503/);
await assert.rejects(loadActiveFaultCatalog({fetcher:async()=>new Response(new Uint8Array(2*1024*1024+1))}),/too large/);
await assert.rejects(loadActiveFaultCatalog({fetcher:async()=>new Response(tile([]))}),/No usable/);
const aborted=new AbortController();aborted.abort();
await assert.rejects(loadActiveFaultCatalog({signal:aborted.signal,fetcher}));
assert.equal((await loadActiveFaultCatalog({fetcher})).length,2,"a failed request must not poison later retries");
console.log("Active-fault simulation: official attributes, Mw/Mj, dip direction, finite source, crustal intensity/EEW, bounded tile loading, deduplication and retry passed.");
