import assert from "node:assert/strict";
import { createSimulationGroundLoader, simulationGroundMeshCode, getSimulationGround } from "../src/simulation/groundModel.js";
import { estimateReferenceIntensity } from "../src/simulation/intensityModel.js";
import { prepareEarthquakeSimulation } from "../src/simulation/earthquakeSimulation.js";

const coordinates = [139.76, 35.68];
assert.equal(simulationGroundMeshCode(coordinates), "53394610");
assert.equal(simulationGroundMeshCode([140, 36]), "54400000", "mesh boundaries use the north/east cell");
assert.equal(simulationGroundMeshCode([-10, 40]), null);
const model = { type: "J-SHIS ground model 1km mesh aggregate", meshValueFormat: ["arv", "avs"], meshes: { "53394610": [2, 200] } };
assert.equal(getSimulationGround(model, coordinates).arv, 2);
for (const arv of [null, "2", 0, -1, Infinity, 100]) assert.equal(getSimulationGround({ meshes: { "53394610": [arv, 200] } }, coordinates), null);
assert.equal(getSimulationGround(model, [140, 36]), null, "missing cell does not use a neighboring ground value");
const values = { magnitude: 5.5, depthKm: 10, ruptureDistanceKm: 100 };
assert.ok(Math.abs(estimateReferenceIntensity({ ...values, groundArv: 2 }) - estimateReferenceIntensity(values) - 1.72 * Math.log10(2)) < 1e-10, "ARV multiplies PGV exactly once");
assert.ok(estimateReferenceIntensity({ ...values, groundArv: .7 }) < estimateReferenceIntensity(values), "hard ground can reduce intensity");
assert.throws(() => estimateReferenceIntensity({ ...values, groundArv: 0 }), RangeError);
let calls = 0;
const load = createSimulationGroundLoader(async () => { calls++; return { ok: calls !== 1, status: 503, json: async () => model }; });
await assert.rejects(load(), /503/);
assert.equal(await load(), model);
assert.equal(await load(), model);
assert.equal(calls, 2, "failure can retry; successful model is reused");
let subsetCalls = 0;
const subsetLoader = createSimulationGroundLoader(async () => { subsetCalls++; return { ok: true, json: async () => ({ ...model, meshes: { ...model.meshes, "54400000": [1, 400] } }) }; });
const subset = await subsetLoader({ coordinates: [coordinates] });
assert.deepEqual(Object.keys(subset.meshes), ["53394610"], "retain only the station catalogue's mesh cells");
assert.equal(await subsetLoader({ coordinates: [coordinates] }), subset);
assert.equal(subsetCalls, 1);
assert.equal((await subsetLoader({ coordinates: [[140, 36]] })).meshes["54400000"][0], 1, "a changed catalogue can load new cells");
await assert.rejects(createSimulationGroundLoader(async () => ({ ok: true, json: async () => ({ meshes: {} }) }))(), /Invalid/);
const aborted = new AbortController(); aborted.abort();
await assert.rejects(load({ signal: aborted.signal }), { name: "AbortError" }, "abort also applies to cached results");
const stations = { "00001": { longitude: 139.76, latitude: 35.68 }, "00002": { longitude: 140, latitude: 36 } };
const plain = await prepareEarthquakeSimulation({}, stations);
const corrected = await prepareEarthquakeSimulation({ groundCorrection: "jshis-1km" }, stations, { groundModel: model });
assert.deepEqual(corrected.groundCoverage, { corrected: 1, total: 2 });
assert.ok(corrected.stations[0].predictedIntensityValue > plain.stations[0].predictedIntensityValue);
assert.equal(corrected.stations[1].predictedIntensityValue, plain.stations[1].predictedIntensityValue, "missing ground stays uncorrected");
assert.equal(corrected.stations[0].pArrivalSec, plain.stations[0].pArrivalSec);
assert.equal(corrected.stations[0].sArrivalSec, plain.stations[0].sArrivalSec);
assert.ok(corrected.reports.at(-1).maxIntensity);
await assert.rejects(prepareEarthquakeSimulation({ groundCorrection: "jshis-1km" }, stations), /Ground model/);
console.log("Simulation ground correction: mesh lookup, amplification, coverage, missing data, retry and cancellation passed");
