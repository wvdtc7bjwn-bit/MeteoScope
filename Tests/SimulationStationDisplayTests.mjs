import assert from "node:assert/strict";
import { prepareEarthquakeSimulation } from "../src/simulation/earthquakeSimulation.js";
const simulation = await prepareEarthquakeSimulation({ magnitude: 6 }, { "001": { code: "001", latitude: 35.68, longitude: 139.76 } });
const peakTime = simulation.stations[0].shakingDecayStartSec;
const peak = simulation.frame(peakTime);
const quiet = simulation.frame(simulation.duration, { intensityDisplay: "maximum" });
assert.equal(quiet.stations.features[0].properties.intensity, peak.stations.features[0].properties.intensity);
assert.equal(quiet.stations.features[0].properties.currentIntensity, "0");
assert.equal(simulation.frame(simulation.duration).stations.features[0].properties.intensity, "0");
assert.deepEqual(quiet.event, simulation.frame(simulation.duration).event, "changing station display must not change EEW estimates");
assert.equal(simulation.frame(0, { intensityDisplay: "maximum" }).stations.features[0].properties.intensity, "0", "rewind cannot leak a future maximum");
const a = simulation.frame(peakTime, { renderOnly: true });
const b = simulation.frame(peakTime + .1, { renderOnly: true });
assert.equal(a.stations.features[0], b.stations.features[0], "reuse immutable unchanged render features");
assert.equal(a.stations.features[0].properties.id, "001");
const full = simulation.frame(peakTime);
for (const [key, value] of Object.entries(a.stations.features[0].properties)) assert.deepEqual(value, full.stations.features[0].properties[key]);
simulation.frame(simulation.duration, { renderOnly: true });
assert.deepEqual(simulation.frame(peakTime, { renderOnly: true }), a, "cached rendering still supports deterministic rewind");
console.log("Simulation display: current/recorded max switching, retained EEW, neutral initial state and immutable render reuse passed");
