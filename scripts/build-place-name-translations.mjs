import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { HISTORICAL_EPICENTER_NAMES } from "../src/jma/historicalEpicenterNames.js";
import { normalizePlaceNameKey } from "../src/ui/placeNameAliases.js";

const root = new URL("../", import.meta.url);
export const outputUrl = new URL("src/ui/placeNamesEn.generated.js", root);

export function renderPlaceNameTranslations(regions, gazetteer) {
  const epicenters = new Map();
  for (const feature of regions.features ?? []) {
    const { name, name_en: english } = feature.properties ?? {};
    if (!name || !english?.trim() || /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(english)) {
      throw new Error("Missing or invalid English epicenter name");
    }
    if (epicenters.has(name) && epicenters.get(name) !== english.trim()) {
      throw new Error(`Conflicting epicenter name: ${name}`);
    }
    epicenters.set(name, english.trim());
  }
  if (!epicenters.size) throw new Error("No epicenter names found");
  // Older monthly catalogues contain regional labels absent from today's table.
  // Preserve their supplied English labels, giving the current names precedence.
  for (const [english, japanese] of Object.entries(HISTORICAL_EPICENTER_NAMES)) {
    if (!epicenters.has(japanese)) epicenters.set(japanese, english);
  }
  const municipalities = new Map();
  for (const [japanese, romaji] of Object.entries(gazetteer.names ?? {})) {
    if (!/(?:市|区|町|村)$/u.test(japanese)) continue;
    const key = normalizePlaceNameKey(japanese);
    if (!romaji || /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]/u.test(romaji)) {
      throw new Error(`Invalid municipality reading: ${japanese}`);
    }
    if (municipalities.has(key) && municipalities.get(key) !== romaji) {
      throw new Error(`Conflicting municipality reading: ${key}`);
    }
    municipalities.set(key, romaji);
  }
  if (!municipalities.size) throw new Error("No municipality names found");
  const serialize = (map) => JSON.stringify(Object.fromEntries([...map].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)), null, 2);
  return `// Generated by scripts/build-place-name-translations.mjs; do not edit.\n`
    + `// Sources: public/data/jma-earthquake-epicenter-regions.geojson (name/name_en),\n`
    + `// src/jma/historicalEpicenterNames.js, public/data/gsi-place-names-romaji.json.\n`
    + `// Names only: no geometry or additional runtime request.\n`
    + `export const EPICENTER_NAMES_EN = Object.freeze(${serialize(epicenters)});\n\n`
    + `export const MUNICIPALITY_ROMAJI = Object.freeze(${serialize(municipalities)});\n`;
}

export async function buildPlaceNameTranslations() {
  const [regions, gazetteer] = await Promise.all([
    readFile(new URL("public/data/jma-earthquake-epicenter-regions.geojson", root), "utf8").then(JSON.parse),
    readFile(new URL("public/data/gsi-place-names-romaji.json", root), "utf8").then(JSON.parse)
  ]);
  const rendered = renderPlaceNameTranslations(regions, gazetteer);
  await writeFile(outputUrl, rendered, "utf8");
  return rendered;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await buildPlaceNameTranslations();
  console.log(`Built place-name translations: ${fileURLToPath(outputUrl)}`);
}
