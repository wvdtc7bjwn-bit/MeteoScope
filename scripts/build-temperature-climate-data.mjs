import {readFile,writeFile,mkdir} from "node:fs/promises";
import {createHash} from "node:crypto";
import {decodeEnvironmentTile,environmentMeshPosition,sampleEnvironmentTile} from "../src/location/environmentMesh.js";
const root=new URL("../",import.meta.url),at=process.argv.indexOf("--stations");
if(at<0||!process.argv[at+1])throw Error("Pass --stations with a locally cached official AMeDAS station table");
const tableBytes=await readFile(process.argv[at+1]),table=JSON.parse(tableBytes);
const normals=JSON.parse(await readFile(new URL("public/data/amedas-daily-high-low-temperature-normals-1991-2020.json",root),"utf8"));
if(normals.schema!==2||normals.quality!=="RMK=8")throw Error("Rebuild quality-checked normals first");
const tiles=new Map(),stations=[];
for(const [id,s]of Object.entries(table)){
  if(!normals.stations[id]||!Number.isFinite(s.alt))continue;
  const longitude=s.lon[0]+s.lon[1]/60,latitude=s.lat[0]+s.lat[1]/60,p=environmentMeshPosition([longitude,latitude]);
  let env=null;
  if(p){if(!tiles.has(p.primary)){try{const b=await readFile(new URL(`public/data/temperature-environment/v1/${p.primary}.bin`,root));tiles.set(p.primary,decodeEnvironmentTile(b.buffer.slice(b.byteOffset,b.byteOffset+b.byteLength),p.primary));}catch{tiles.set(p.primary,null);}}env=sampleEnvironmentTile(tiles.get(p.primary),p);}
  stations.push([id,longitude,latitude,s.alt,env?.sea??null,env?.urban??null]);
}
const data={schema:1,period:normals.period,columns:["id","longitude","latitude","elevation","sea","urban"],
  stationTableSha256:createHash("sha256").update(tableBytes).digest("hex"),stations};
const json=JSON.stringify(data)+"\n",hash=createHash("sha256").update(json).digest("hex").slice(0,12);
const path=`data/temperature-climate/stations-${hash}.json`;
await mkdir(new URL("public/data/temperature-climate/",root),{recursive:true});
await writeFile(new URL(`public/${path}`,root),json);
await writeFile(new URL("src/location/temperatureClimateData.generated.js",root),`// Generated by scripts/build-temperature-climate-data.mjs\nexport const TEMPERATURE_CLIMATE_DATA_PATH = ${JSON.stringify(path)};\n`);
console.log(`Built ${stations.length} climate station records (${Buffer.byteLength(json)} bytes)`);
